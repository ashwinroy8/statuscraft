// Returns festivals occurring within the next N days from today
export function getUpcomingFestivals(daysAhead: number = 7): Array<FestivalData & { daysUntil: number; date: Date }> {
  const today = new Date();
  const result: Array<FestivalData & { daysUntil: number; date: Date }> = [];

  for (const festival of FESTIVALS) {
    const [month, day] = festival.monthDay.split("-").map(Number);
    const thisYear = new Date(today.getFullYear(), month - 1, day);
    const nextYear = new Date(today.getFullYear() + 1, month - 1, day);

    // Check this year and next year (handles Dec → Jan wrap)
    for (const festDate of [thisYear, nextYear]) {
      const daysUntil = Math.floor((festDate.getTime() - today.getTime()) / (1000 * 60 * 60 * 24));
      if (daysUntil >= 0 && daysUntil <= daysAhead) {
        result.push({ ...festival, daysUntil, date: festDate });
        break;
      }
    }
  }

  return result.sort((a, b) => a.daysUntil - b.daysUntil);
}
